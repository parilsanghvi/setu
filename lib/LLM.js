const https = require('https');

class LLM {
    constructor() {
        this.apiKey = process.env.OPENAI_API_KEY;
        this.endpoint = 'https://api.openai.com/v1/chat/completions';
    }

    async generate(systemPrompt, userPrompt, model = 'gpt-4o') {
        if (!this.apiKey) {
            console.warn('[LLM] ⚠️ No API Key found. Returning mock response.');
            if (userPrompt.includes('Evaluate this architectural spec') || userPrompt.includes('Evaluate this UI/Frontend spec') || userPrompt.includes('Evaluate this Database/Schema spec')) {
                return "VETO: This is a mock veto for testing purposes. No API key detected.";
            }
            if (userPrompt.includes("Review this junior engineer's plan")) {
                return "RISKY: This plan involves dropping tables or core rewrites. Escalating to human.";
            }
            return JSON.stringify({
                slug: "mock-skill-generated",
                description: "This is a mock skill generated by Drona without an API key. Use when testing.",
                content: "# Mock Skill\n\nThis is a generated skill.\n\n## Steps\n1. Do this.\n2. Do that."
            });
        }

        const data = JSON.stringify({
            model: model,
            messages: [
                { role: 'system', content: systemPrompt },
                { role: 'user', content: userPrompt }
            ]
        });

        const options = {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'Authorization': `Bearer ${this.apiKey}`,
                'Content-Length': data.length
            }
        };

        return new Promise((resolve, reject) => {
            const req = https.request(this.endpoint, options, (res) => {
                let body = '';
                res.on('data', (chunk) => body += chunk);
                res.on('end', () => {
                    if (res.statusCode >= 400) {
                        reject(new Error(`LLM API Error: ${res.statusCode} ${body}`));
                        return;
                    }
                    try {
                        const json = JSON.parse(body);
                        resolve(json.choices[0].message.content);
                    } catch (e) {
                        reject(e);
                    }
                });
            });

            req.on('error', (e) => reject(e));
            req.write(data);
            req.end();
        });
    }
}

module.exports = new LLM();
